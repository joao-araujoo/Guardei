import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const SRC_ROOT = path.join(ROOT, 'src');
const OUTPUT = path.join(SRC_ROOT, 'lib', 'localIconify.js');
const LUCIDE_ICON_SET_COMMIT = '156ecc4a919af31626c297dc9cac451970622841';
const SOURCE_URL = `https://raw.githubusercontent.com/iconify/icon-sets/${LUCIDE_ICON_SET_COMMIT}/json/lucide.json`;

// Keep the Guardei-facing names stable even when Lucide renames canonical files.
const LEGACY_ALIASES = Object.freeze({
  'bar-chart-3': 'chart-no-axes-column',
  'check-circle-2': 'circle-check',
  'circle-help': 'circle-question-mark',
  'code-2': 'code-xml',
  home: 'house',
  'plus-circle': 'circle-plus'
});

async function collectSourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collectSourceFiles(fullPath));
    else if (/\.(?:js|jsx|mjs|html)$/i.test(entry.name)) files.push(fullPath);
  }
  return files;
}

async function collectRequestedIcons() {
  const files = await collectSourceFiles(SRC_ROOT);
  const names = new Set();
  const matcher = /lucide:([a-z0-9-]+)/g;
  for (const file of files) {
    const source = await readFile(file, 'utf8');
    for (const match of source.matchAll(matcher)) names.add(match[1]);
  }
  names.add('bookmark');
  return [...names].sort();
}

function resolveBody(iconSet, requestedName) {
  const candidates = [requestedName, LEGACY_ALIASES[requestedName]].filter(Boolean);
  for (const candidate of candidates) {
    if (iconSet.icons?.[candidate]?.body) return iconSet.icons[candidate].body;
    const alias = iconSet.aliases?.[candidate];
    if (alias?.parent && !alias.rotate && !alias.hFlip && !alias.vFlip && iconSet.icons?.[alias.parent]?.body) {
      return iconSet.icons[alias.parent].body;
    }
  }
  return null;
}

function buildRuntime(iconBodies, requestedNames) {
  const catalog = JSON.stringify(iconBodies, null, 2);
  const names = JSON.stringify(requestedNames, null, 2);
  return `// Generated by scripts/generate-local-icons.mjs from Iconify's Lucide dataset.\n// Source commit: ${LUCIDE_ICON_SET_COMMIT}. Runtime is fully local; do not hand-edit this file.\n\nconst ICON_BODIES = Object.freeze(${catalog});\n\nexport const LOCAL_LUCIDE_ICON_NAMES = Object.freeze(${names});\nconst FALLBACK_ICON = 'bookmark';\n\nclass LocalIconifyIcon extends HTMLElement {\n  static get observedAttributes() { return ['icon']; }\n\n  connectedCallback() {\n    this.renderIcon();\n  }\n\n  attributeChangedCallback(name, previousValue, nextValue) {\n    if (name === 'icon' && previousValue !== nextValue && this.isConnected) this.renderIcon();\n  }\n\n  renderIcon() {\n    const value = String(this.getAttribute('icon') || 'lucide:' + FALLBACK_ICON);\n    const [prefix, requestedName] = value.split(':');\n    const body = prefix === 'lucide' ? ICON_BODIES[requestedName] : null;\n    const safeBody = body || ICON_BODIES[FALLBACK_ICON];\n    if (!body) this.dataset.iconMissing = requestedName || value;\n    else delete this.dataset.iconMissing;\n\n    this.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="1em" height="1em" aria-hidden="true" focusable="false" style="display:block">' + safeBody + '</svg>';\n  }\n}\n\nif (globalThis.customElements && !customElements.get('iconify-icon')) {\n  customElements.define('iconify-icon', LocalIconifyIcon);\n}\n`;
}

const requestedNames = await collectRequestedIcons();
const response = await fetch(SOURCE_URL, {
  headers: { 'user-agent': 'Guardei-local-icon-generator' },
  signal: AbortSignal.timeout(20_000)
});
if (!response.ok) throw new Error(`Falha ao carregar catálogo Lucide (${response.status}).`);
const iconSet = await response.json();

const missing = [];
const iconBodies = {};
for (const name of requestedNames) {
  const body = resolveBody(iconSet, name);
  if (!body) missing.push(name);
  else iconBodies[name] = body;
}
if (missing.length) throw new Error(`Ícones Lucide sem resolução local: ${missing.join(', ')}`);

await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, buildRuntime(iconBodies, requestedNames), 'utf8');
console.log(`Catálogo local gerado com ${requestedNames.length} ícones em ${path.relative(ROOT, OUTPUT)}.`);
